#!/usr/bin/env node
// Builds a ready-to-load copy of the extension with the team's relay URL and token baked in,
// so teammates just unzip and "Load unpacked". The repo's extension/config.js stays empty.
//
//   node tools/package-extension.mjs --url wss://hybrid-audio-relay.<you>.workers.dev --token <TEAM_TOKEN>
//
// Output: dist/hybrid-audio/ (folder to load) and dist/hybrid-audio.zip (to share).
// dist/ is git-ignored: it contains the token. Share it only with the team.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : undefined; };

let url = arg('url') || '';
const token = arg('token') || '';
if (!url || !token) {
  console.error('usage: node tools/package-extension.mjs --url wss://<relay host> --token <TEAM_TOKEN>');
  process.exit(1);
}
url = url.trim().replace(/\/+$/, '').replace(/^https:/i, 'wss:').replace(/^http:/i, 'ws:');
if (!/^wss?:\/\/[^\s/]+/i.test(url)) { console.error(`bad --url: ${url}`); process.exit(1); }
if (!/^[\x21-\x7e]{8,200}$/.test(token)) { console.error('bad --token (8-200 printable chars)'); process.exit(1); }

const src = path.join(root, 'extension');
const distDir = path.join(root, 'dist');
const out = path.join(distDir, 'hybrid-audio');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(distDir, { recursive: true });
fs.cpSync(src, out, { recursive: true });

fs.writeFileSync(path.join(out, 'config.js'),
  '// Generated by tools/package-extension.mjs. Contains the team token: share only with the team.\n' +
  `export const BACKEND_URL = ${JSON.stringify(url)};\n` +
  `export const TEAM_TOKEN = ${JSON.stringify(token)};\n`);

const zip = path.join(distDir, 'hybrid-audio.zip');
fs.rmSync(zip, { force: true });
try {
  execFileSync('zip', ['-qr', zip, 'hybrid-audio'], { cwd: distDir });
} catch {
  console.warn('zip not available; share the folder instead.');
}
const { version } = JSON.parse(fs.readFileSync(path.join(out, 'manifest.json'), 'utf8'));
console.log(`Built Hybrid Audio ${version}\n  folder: ${out}\n  zip:    ${fs.existsSync(zip) ? zip : '(none)'}\n  relay:  ${url}`);
